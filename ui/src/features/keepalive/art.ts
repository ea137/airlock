// The game's sprites, drawn as rows of digits. Each digit is a slot and
// each sprite names the paints that fill its slots (look.ts turns a paint
// into the theme's colour), so one drawing works in every theme. Slot 1 is
// the outline. Characters face down; the atlas makes a back view by
// painting over the face (slots 3, 4 and 6), and mirrors what faces right.

export type Paint =
  | 'ink'
  | 'text'
  | 'dim'
  | 'light'
  | 'accent'
  | 'accentLight'
  | 'ok'
  | 'warn'
  | 'danger'
  | 'dangerLight'
  | 'hue'
  | 'hueLight'
  | 'hueDark'
  | 'skin'
  | 'cron'
  | 'cronLight'
  | 'sudo'
  | 'sudoLight'
  | 'float'
  | 'floatLight'
  | 'tel'
  | 'telLight'
  | 'void'
  | 'voidLight'
  | 'decor'
  | 'decorLight'
  | 'wallTop'
  | 'wallLight'
  | 'wallLine'
  | 'wallFace'
  | 'floor'
  | 'floor2'
  | 'line';

export type Art = { w: number; h: number; paint: Paint[]; rows: string[] };

export function art(paint: Paint[], drawing: string): Art {
  const rows = drawing
    .split('\n')
    .map((row) => row.trim())
    .filter((row) => row.length > 0);
  return { w: rows[0]?.length ?? 0, h: rows.length, paint, rows };
}


// The hand-made set pieces levels are stitched from. Each is drawn in
// characters, bottom row on the level's ground; the generator raises and
// lowers them, mirrors them, fills the enemy slots from the zone's own
// bugs, and picks which key spots hold keys.
//
// Tiles are in tiles.ts (CHAR_TILE). The other characters:
//   e  a ground bug, from the zone's roster     E  a flying one
//   d  a ceiling dripper slot                   c z v j y t p  a set bug
//   r  a cron turret (a block that fires)       m  a moving platform; `,` is its track
//   M  a lift (moves up and down its `,` track) f  a platform that falls when stood on
//   C  checkpoint  F  the deploy flag  @  start  $  the backdoor (secret exit)
//
// A chunk starts and ends on two columns of ground with room above, so any
// two fit together. Tags: the category first, then twists it shows off.


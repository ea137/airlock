function parse(raw: Raw): ChunkDef {
  const [id, tags, diff, art] = raw;
  const rows = art.split('\n').filter((row) => row.length > 0);
  const w = Math.max(...rows.map((row) => row.length));
  return { id, tags: tags.split(' '), diff, rows: rows.map((row) => row.padEnd(w, '.')), w };
}

export const CHUNKS: ChunkDef[] = RUN.map(parse);
export const CLIMBS: ChunkDef[] = CLIMB.map(parse);
export const BONUS_ROOMS: ChunkDef[] = BONUS.map(parse);
export const ARENAS: ChunkDef[] = ARENA.map(parse);

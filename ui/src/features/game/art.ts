// The game's art, drawn as rows of digits. Each digit is a colour slot
// (1 outline, 2 body, 3 light, 4 detail, 5 accent; '.' is clear) and each
// sprite names the skin colours that fill its slots, so one drawing works
// in every theme. Everything faces right; the atlas mirrors it.

export type Paint =
  | 'ink'
  | 'text'
  | 'dim'
  | 'accent'
  | 'accentLight'
  | 'ok'
  | 'warn'
  | 'danger'
  | 'dangerLight'
  | 'ground'
  | 'groundDark'
  | 'light'
  | 'zone'
  | 'h1'
  | 'h2'
  | 'h3'
  | 'h5'
  | 'h6'
  | 'h7';

export type Art = { w: number; h: number; paint: Paint[]; rows: string[] };

function art(paint: Paint[], drawing: string): Art {
  const rows = drawing
    .split('\n')
    .map((row) => row.trim())
    .filter((row) => row.length > 0);
  return { w: rows[0]?.length ?? 0, h: rows.length, paint, rows };
}

function variants(prefixes: Record<string, Paint[]>, drawings: Record<string, string>): Record<string, Art> {
  const out: Record<string, Art> = {};
  for (const [prefix, paint] of Object.entries(prefixes)) {
    for (const [name, drawing] of Object.entries(drawings)) out[`${prefix}${name}`] = art(paint, drawing);
  }
  return out;
}


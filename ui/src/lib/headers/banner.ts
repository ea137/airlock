// Big block letters for the hacker theme's banner, five rows high.

const GLYPHS: Record<string, string[]> = {
  A: ['.###.', '#...#', '#####', '#...#', '#...#'],
  C: ['.####', '#....', '#....', '#....', '.####'],
  E: ['#####', '#....', '####.', '#....', '#####'],
  F: ['#####', '#....', '####.', '#....', '#....'],
  H: ['#...#', '#...#', '#####', '#...#', '#...#'],
  I: ['#####', '..#..', '..#..', '..#..', '#####'],
  K: ['#...#', '#..#.', '###..', '#..#.', '#...#'],
  L: ['#....', '#....', '#....', '#....', '#####'],
  M: ['#...#', '##.##', '#.#.#', '#...#', '#...#'],
  N: ['#...#', '##..#', '#.#.#', '#..##', '#...#'],
  O: ['.###.', '#...#', '#...#', '#...#', '.###.'],
  R: ['####.', '#...#', '####.', '#..#.', '#...#'],
  S: ['.####', '#....', '.###.', '....#', '####.'],
  T: ['#####', '..#..', '..#..', '..#..', '..#..'],
  W: ['#...#', '#...#', '#.#.#', '##.##', '#...#'],
  Y: ['#...#', '.#.#.', '..#..', '..#..', '..#..'],
};

const BLANK = ['.....', '.....', '.....', '.....', '.....'];

/** `word` in block letters, one string per row; letters it has no glyph for are blank. */
export function banner(word: string): string[] {
  const letters = [...word.toUpperCase()].map((letter) => GLYPHS[letter] ?? BLANK);
  return [0, 1, 2, 3, 4].map((row) =>
    letters
      .map((glyph) => glyph[row] ?? '.....')
      .join(' ')
      .replace(/#/g, '█')
      .replace(/\./g, ' '),
  );
}
